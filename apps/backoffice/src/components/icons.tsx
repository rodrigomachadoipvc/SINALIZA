export const STATUS_ICON_COMPONENTS: Record<OccurrenceStatus, LucideIcon> = {
  RECEBIDA: Clock,
  EM_ANALISE: Search,
  EM_RESOLUCAO: Flag,
  RESOLVIDA: CircleCheck,
  REJEITADA: X,
  DUPLICADA: Copy,
  ANULADA: Ban,
};

export function CategoryIcon({ name, size = 20 }: { name: string; size?: number }) {
  const Icon = CATEGORY_ICON_COMPONENTS[name as CategoryIconName] ?? Ellipsis;
  return <Icon size={size} strokeWidth={2} aria-hidden="true" />;
}
